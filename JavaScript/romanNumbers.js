let number = Number(prompt("Введите число от 1 до 9:"));

if (number === 1) {
    console.log("I");
} else if (number === 2) {
    console.log("II");
} else if (number === 3) {
    console.log("III");
} else if (number === 4) {
    console.log("IV");
} else if (number === 5) {
    console.log("V");
} else if (number === 6) {
    console.log("VI");
} else if (number === 7) {
    console.log("VII");
} else if (number === 8) {
    console.log("VIII");
} else if (number === 9) {
    console.log("IX");
} else {
    console.log("Введите число от 1 до 9");
}